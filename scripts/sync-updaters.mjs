// Each independently installed extension gets its own local copies. Nothing is
// loaded from another extension, remote script or runtime code-generation service.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const tools = JSON.parse(await fs.readFile(path.join(root, 'scripts/updater-tools.json'), 'utf8'));
export const sharedFiles = ['updater.js', 'update-core.js', 'update-network.js', 'update-store.js', 'update-session.js'];
const check = process.argv.includes('--check');
let differences = 0;
for (const tool of tools) {
  const contents = new Map(await Promise.all(sharedFiles.map(async file => [file, await fs.readFile(path.join(root, 'shared/updater', file), 'utf8')])));
  contents.set('update-config.js', '// Generated by scripts/sync-updaters.mjs; edit scripts/updater-tools.json.\nexport const UPDATE_CONFIG = Object.freeze(' + JSON.stringify(tool.config, null, 2) + ');\n');
  for (const [file, expected] of contents) {
    const target = path.join(root, tool.directory, file);
    const actual = await fs.readFile(target, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; return null; });
    if (actual !== expected) {
      differences++;
      if (check) console.error('Updater source differs:', path.relative(root, target));
      else await fs.writeFile(target, expected);
    }
  }
}
if (check && differences) process.exitCode = 1;
console.log(check ? `${tools.length} updater copies checked; ${differences} differences` : `${tools.length} updaters synchronized; ${differences} files updated`);
